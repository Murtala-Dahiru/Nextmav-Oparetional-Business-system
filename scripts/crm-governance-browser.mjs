import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { createClient } from '@supabase/supabase-js';
process.loadEnvFile('.env');
const { chromium } = await import(pathToFileURL(join(tmpdir(), 'nextmav-browser/node_modules/playwright/index.mjs')).href);
const base = process.env.APP_URL || 'http://localhost:3037';
const admin = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { persistSession: false } });
const fixture = { email: `governance-${randomUUID()}@example.invalid`, password: `Test!${randomUUID()}9a` };
const user = await admin.auth.admin.createUser({ email: fixture.email, password: fixture.password, email_confirm: true, user_metadata: { first_name: 'Governance', last_name: 'Acceptance' } });
assert.ifError(user.error); fixture.userId = user.data.user.id;
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
context.setDefaultTimeout(90000);
let passed = 0;
const check = (ok, label) => { assert.ok(ok, label); console.log('PASS ' + label); passed++; };
mkdirSync('docs/governance-evidence', { recursive: true });
async function api(path, data) {
  const response = data === undefined ? await context.request.get(base + path) : await context.request.post(base + path, { data });
  const body = await response.json(); assert.ok(response.ok(), `${path}: ${response.status()} ${JSON.stringify(body)}`); return body.data;
}
try {
  await api('/api/auth/login', { email: fixture.email, password: fixture.password });
  fixture.orgId = (await api('/api/organizations', { name: 'Governance acceptance Real Estate ' + randomUUID().slice(0, 6) })).id;
  await api('/api/auth/login', {email:fixture.email,password:fixture.password});
  writeFileSync(join(tmpdir(), 'nextmav-governance-fixture.json'), JSON.stringify(fixture));
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/dashboard', { waitUntil: 'domcontentloaded', timeout: 180000 });
  await page.getByRole('button', { name: 'Customers & revenue', exact: true }).click();
  async function section(value, label) {
    const mobile = page.getByRole('combobox', { name: 'CRM destination' });
    if (await mobile.isVisible()) await mobile.selectOption(value); else await page.getByRole('button', { name: label, exact: true }).click();
  }
  await section('settings', 'Settings');
  await page.getByRole('button', { name: 'Create field', exact: true }).click();
  await page.getByLabel('Label', { exact: true }).fill('Property Type');
  await page.getByLabel('Internal identifier').fill('property_type');
  await page.getByLabel('Field type').selectOption('dropdown');
  await page.getByLabel('Options (one per line; existing options are retained)').fill('Residential\nCommercial');
  await page.getByLabel('Required', { exact: true }).check();
  await page.getByRole('button', { name: 'Save field', exact: true }).click();
  await page.getByText('property_type · dropdown', { exact: false }).waitFor();
  check(true, 'Field created through actual settings UI');
  const definitions = await api('/api/crm/settings/fields?object=leads'); const field = definitions.find(f => f.key === 'property_type');
  assert.ok(field);
  await page.getByRole('button', { name: 'Layouts', exact: true }).click();
  await page.getByRole('button', { name: 'Add section', exact: true }).click();
  await page.getByLabel('Section title').fill('Property requirements');
  await page.getByRole('combobox', { name: 'Add field to Property requirements' }).selectOption(field.id);
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  await page.getByText('Saved revision 1', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Preview layout', exact: true }).click();
  await page.getByLabel('Layout preview').getByText('Property requirements', { exact: true }).waitFor();
  check(true, 'Layout draft and preview work in UI');
  page.once('dialog', d => d.accept());
  await page.getByRole('button', { name: 'Publish', exact: true }).click();
  await page.getByText('Saved revision 2', { exact: false }).waitFor();
  check((await api('/api/crm/settings/layouts?object=leads')).published[0].fields[0] === field.id, 'Published layout persists through API');
  await section('leads', 'Leads');
  await page.getByRole('button', { name: 'Add lead', exact: true }).first().scrollIntoViewIfNeeded();
  await page.getByRole('button', { name: 'Add lead', exact: true }).first().press('Enter');
  const dialog = page.getByRole('dialog');
  // Existing standard labels are visual labels without htmlFor; identify the first name input by form order.
  await dialog.locator('input').first().fill('Governance prospect');
  await dialog.getByLabel('Property Type *', { exact: true }).selectOption('Residential');
  await dialog.getByRole('button', { name: 'Add lead', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const records = await api('/api/crm/leads?search=Governance%20prospect');
  const lead = records.find(r => r.firstName === 'Governance prospect'); assert.ok(lead); fixture.leadId = lead.id;
  check(lead.customValues[field.id] === 'Residential', 'Custom field form saves with the record');
  await page.getByRole('combobox', { name: 'Filter custom field' }).selectOption(field.id);
  await page.getByRole('combobox', { name: 'Custom field match' }).selectOption('Commercial');
  await page.getByRole('button', { name: 'Apply filter', exact: true }).click();
  const filtered = await api('/api/crm/leads?custom=' + encodeURIComponent(JSON.stringify({ [field.id]: 'Commercial' })));
  check(filtered.length === 0, 'Custom filter excludes nonmatching records');
  await page.getByRole('button', { name: 'Clear custom filter', exact: true }).click();
  await page.getByRole('row').filter({hasText:'Governance prospect'}).click();
  await page.getByRole('dialog').getByText('Residential', { exact: true }).waitFor();
  check(true, 'Custom field value appears in actual record details');
  await page.screenshot({ path: 'docs/governance-evidence/record-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Record fits mobile viewport');
  await page.screenshot({ path: 'docs/governance-evidence/record-mobile.png' });
  const invalid = await context.request.post(base + '/api/crm/leads', { data: { firstName: 'Invalid', customValues: { [field.id]: 'Bad option' } } });
  check(invalid.status() >= 400 && invalid.status() < 500, 'API rejects invalid typed value');
  const missing = await context.request.post(base + '/api/crm/leads', { data: { firstName: 'Missing required' } });
  check(missing.status() >= 400 && missing.status() < 500, 'API rejects missing required value');
  check(errors.length === 0, 'No browser runtime errors');
  writeFileSync(join(tmpdir(), 'nextmav-governance-fixture.json'), JSON.stringify(fixture));
  console.log(`${passed} browser/API checks passed. Synthetic tenant retained for review; no messages sent.`);
} finally { await browser.close(); }
