-- ───────────────────────────────────────────────────────────────────────────
--  3. Document history
-- ───────────────────────────────────────────────────────────────────────────
--
--  `workspace_page_versions` has existed since 0003 and has never had a row
--  written to it, so "track document history" had a table and no history. A
--  trigger rather than an endpoint, because the page is edited from the
--  document view, the rename control and the move dialog, and a snapshot that
--  three call sites have to remember to take is one that eventually is not.
--
--  The snapshot records the state *before* the edit, which is what "restore"
--  needs — a history whose newest entry is identical to the live page is a
--  list of duplicates.

CREATE OR REPLACE FUNCTION public.snapshot_page_version()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  -- Only substantive changes. Starring a page, moving it, or touching
  -- `updated_at` is not a revision anybody wants to scroll past.
  IF NEW.content IS NOT DISTINCT FROM OLD.content
     AND NEW.title IS NOT DISTINCT FROM OLD.title THEN
    RETURN NEW;
  END IF;

  INSERT INTO workspace_page_versions (page_id, content, title, version, edited_by)
  VALUES (OLD.id, OLD.content, OLD.title, OLD.version, OLD.last_edited_by)
  ON CONFLICT (page_id, version) DO NOTHING;

  NEW.version := OLD.version + 1;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_snapshot_page_version ON workspace_pages;
CREATE TRIGGER trg_snapshot_page_version
  BEFORE UPDATE ON workspace_pages
  FOR EACH ROW EXECUTE FUNCTION public.snapshot_page_version();

/**
 * History is pruned to the last fifty revisions per page.
 *
 * A document edited all day otherwise accumulates thousands of rows nobody
 * will ever open, and the version list becomes unusable long before the
 * storage matters.
 */
CREATE OR REPLACE FUNCTION public.prune_page_versions()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  DELETE FROM workspace_page_versions
  WHERE page_id = NEW.page_id
    AND id NOT IN (
      SELECT id FROM workspace_page_versions
      WHERE page_id = NEW.page_id
      ORDER BY version DESC
      LIMIT 50
    );
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_prune_page_versions ON workspace_page_versions;
CREATE TRIGGER trg_prune_page_versions
  AFTER INSERT ON workspace_page_versions
  FOR EACH ROW EXECUTE FUNCTION public.prune_page_versions();

-- The versions table is scoped through its page, which now carries a sharing
-- rule; 0005 scoped it to the whole organisation.
DROP POLICY IF EXISTS page_versions_select ON workspace_page_versions;
CREATE POLICY page_versions_select ON workspace_page_versions FOR SELECT TO authenticated
  USING (public.page_permission(page_id) IS NOT NULL);

DROP POLICY IF EXISTS page_versions_insert ON workspace_page_versions;
CREATE POLICY page_versions_insert ON workspace_page_versions FOR INSERT TO authenticated
  WITH CHECK (public.page_permission(page_id) IN ('edit', 'manage'));


-- ───────────────────────────────────────────────────────────────────────────
--  4. Files
-- ───────────────────────────────────────────────────────────────────────────
--
--  `files` has held metadata for Supabase Storage objects since 0003 and the
--  application has never written to it: the uploader in the workspace made an
--  object URL in the browser, showed a progress bar driven by setInterval, and
--  reported success. Nothing left the tab. These columns are what a file
--  browser needs on top of what was already there.

ALTER TABLE files
  ADD COLUMN IF NOT EXISTS description text NOT NULL DEFAULT '',
  /** Superseded uploads keep their row; the newest version wins the listing. */
  ADD COLUMN IF NOT EXISTS version int NOT NULL DEFAULT 1,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

CREATE INDEX IF NOT EXISTS idx_files_page ON files (page_id) WHERE deleted_at IS NULL;

/**
 * Renaming and moving a file is an update, and there was no UPDATE policy.
 *
 * 0005 gave `files` select, insert and delete only, so a rename silently
 * affected zero rows and the endpoint answered 200. Restricted to the uploader
 * and administrators, matching the delete rule.
 */
DROP POLICY IF EXISTS files_update ON files;
CREATE POLICY files_update ON files FOR UPDATE TO authenticated
  USING (
    organization_id = ANY (public.auth_org_ids())
    AND (uploaded_by = public.auth_member_id(organization_id)
         OR public.is_org_admin(organization_id))
  )
  WITH CHECK (organization_id = ANY (public.auth_org_ids()));


