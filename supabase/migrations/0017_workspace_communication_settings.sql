/**
 * Open a direct conversation with a colleague, creating it if needed.
 *
 * An RPC rather than a POST that the client assembles, for two reasons: the
 * pair must be unique in both directions — otherwise Ada messaging Grace and
 * Grace messaging Ada produce two half-empty threads — and creating the
 * channel and both memberships has to be one atomic act, or a crash between
 * them leaves a conversation nobody is in.
 */
CREATE OR REPLACE FUNCTION public.open_direct_channel(org uuid, other_member uuid)
RETURNS uuid
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  me      uuid := public.auth_member_id(org);
  chan    uuid;
  slug    text;
BEGIN
  IF me IS NULL THEN
    RAISE EXCEPTION 'You are not a member of this organization.'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF NOT public.can_access_module(org, 'communication') THEN
    RAISE EXCEPTION 'Your role does not have access to messaging.'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF other_member = me THEN
    RAISE EXCEPTION 'You cannot start a conversation with yourself.'
      USING ERRCODE = 'check_violation';
  END IF;

  -- The other party must be a current employee of the same organisation. This
  -- is what stops a client login being pulled into an internal thread.
  IF NOT EXISTS (
    SELECT 1 FROM organization_members om
    WHERE om.id = other_member
      AND om.organization_id = org
      AND om.is_active = true
      AND om.role <> 'client'
  ) THEN
    RAISE EXCEPTION 'That person cannot be messaged.' USING ERRCODE = 'check_violation';
  END IF;

  -- Existing thread: a direct channel whose membership is exactly these two.
  SELECT c.id INTO chan
  FROM channels c
  WHERE c.organization_id = org
    AND c.type = 'direct'
    AND (SELECT COUNT(*) FROM channel_members cm WHERE cm.channel_id = c.id) = 2
    AND EXISTS (SELECT 1 FROM channel_members cm WHERE cm.channel_id = c.id AND cm.member_id = me)
    AND EXISTS (SELECT 1 FROM channel_members cm WHERE cm.channel_id = c.id AND cm.member_id = other_member)
  LIMIT 1;

  IF chan IS NOT NULL THEN
    RETURN chan;
  END IF;

  -- Deterministic, so two people opening the thread at the same moment cannot
  -- create two channels with different names.
  slug := 'dm-' || LEAST(me::text, other_member::text) || '-' || GREATEST(me::text, other_member::text);

  INSERT INTO channels (organization_id, name, display_name, description, type,
                        created_by, join_policy, post_policy)
  VALUES (org, slug, NULL, '', 'direct', me, 'invite', 'members')
  RETURNING id INTO chan;

  INSERT INTO channel_members (channel_id, member_id, role)
  VALUES (chan, me, 'owner'), (chan, other_member, 'member')
  ON CONFLICT (channel_id, member_id) DO NOTHING;

  RETURN chan;
END;
$$;

GRANT EXECUTE ON FUNCTION public.open_direct_channel(uuid, uuid) TO authenticated;

/**
 * Everything the sidebar needs, in one query.
 *
 * The module was fetching the channel list and then one request per channel to
 * find its last message — twenty channels meant twenty-one round trips on
 * every load, and the unread badge was hard-coded to zero because there was
 * nothing to read it from. `last_read_at` on the membership has been the right
 * source since 0003; this is the query that finally uses it.
 */
CREATE OR REPLACE FUNCTION public.channel_overview(org uuid)
RETURNS TABLE (
  channel_id      uuid,
  name            text,
  display_name    text,
  description     text,
  topic           text,
  type            channel_type,
  post_policy     text,
  join_policy     text,
  is_archived     boolean,
  created_by      uuid,
  member_count    int,
  message_count   int,
  unread_count    int,
  is_member       boolean,
  is_admin        boolean,
  my_role         text,
  last_message    text,
  last_message_at timestamptz,
  last_sender     text,
  counterpart_id   uuid,
  counterpart_name text,
  counterpart_avatar text
)
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  WITH me AS (SELECT public.auth_member_id(org) AS id),
  visible AS (
    SELECT c.*
    FROM channels c, me
    WHERE c.organization_id = org
      AND public.can_access_module(org, 'communication')
      AND (
        c.type IN ('public', 'announcement')
        OR EXISTS (SELECT 1 FROM channel_members cm
                   WHERE cm.channel_id = c.id AND cm.member_id = me.id)
        OR public.is_org_admin(org)
      )
  )
  SELECT
    v.id,
    v.name,
    v.display_name,
    v.description,
    v.topic,
    v.type,
    v.post_policy,
    v.join_policy,
    v.is_archived,
    v.created_by,
    (SELECT COUNT(*)::int FROM channel_members cm WHERE cm.channel_id = v.id),
    (SELECT COUNT(*)::int FROM messages m WHERE m.channel_id = v.id AND m.deleted_at IS NULL),
    (SELECT COUNT(*)::int FROM messages m
      WHERE m.channel_id = v.id
        AND m.deleted_at IS NULL
        AND m.sender_id IS DISTINCT FROM me.id
        AND m.created_at > COALESCE(
              (SELECT cm.last_read_at FROM channel_members cm
                WHERE cm.channel_id = v.id AND cm.member_id = me.id),
              '-infinity'::timestamptz)),
    EXISTS (SELECT 1 FROM channel_members cm
            WHERE cm.channel_id = v.id AND cm.member_id = me.id),
    public.is_channel_admin(v.id),
    (SELECT cm.role FROM channel_members cm
      WHERE cm.channel_id = v.id AND cm.member_id = me.id),
    last_msg.body,
    last_msg.created_at,
    last_msg.sender_name,
    -- For a direct message the sidebar shows the other person, not the slug.
    dm.member_id,
    dm.full_name,
    dm.avatar_url
  FROM visible v, me
  LEFT JOIN LATERAL (
    SELECT m.body, m.created_at, p.full_name AS sender_name
    FROM messages m
    LEFT JOIN organization_members om ON om.id = m.sender_id
    LEFT JOIN profiles p ON p.id = om.user_id
    WHERE m.channel_id = v.id AND m.deleted_at IS NULL
    ORDER BY m.created_at DESC
    LIMIT 1
  ) last_msg ON true
  LEFT JOIN LATERAL (
    SELECT cm.member_id, p.full_name, p.avatar_url
    FROM channel_members cm
    JOIN organization_members om ON om.id = cm.member_id
    JOIN profiles p ON p.id = om.user_id
    WHERE v.type = 'direct'
      AND cm.channel_id = v.id
      AND cm.member_id IS DISTINCT FROM me.id
    LIMIT 1
  ) dm ON true
  ORDER BY COALESCE(last_msg.created_at, v.created_at) DESC;
$$;

GRANT EXECUTE ON FUNCTION public.channel_overview(uuid) TO authenticated;

/**
 * A new message notifies the people who are in the conversation.
 *
 * Direct messages and mentions only. Notifying every member of every channel
 * on every message is how a notification tray becomes something people learn
 * to ignore, and the unread badge already covers "there is something new in
 * this channel".
 */
CREATE OR REPLACE FUNCTION public.notify_message()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  chan      channels;
  audience  uuid[];
  who       text;
  label     text;
BEGIN
  SELECT * INTO chan FROM channels WHERE id = NEW.channel_id;
  IF NOT FOUND THEN RETURN NEW; END IF;

  SELECT p.full_name INTO who
  FROM organization_members om JOIN profiles p ON p.id = om.user_id
  WHERE om.id = NEW.sender_id;

  IF chan.type = 'direct' THEN
    SELECT COALESCE(array_agg(cm.member_id), ARRAY[]::uuid[]) INTO audience
    FROM channel_members cm WHERE cm.channel_id = chan.id;

    PERFORM public.notify_members(
      NEW.organization_id, audience, 'message',
      COALESCE(who, 'A colleague') || ' sent you a message',
      left(NEW.body, 140), 'channel', chan.id, '/dashboard?module=communication'
    );
  ELSIF array_length(NEW.mentions, 1) > 0 THEN
    label := COALESCE(NULLIF(chan.display_name, ''), '#' || chan.name);
    PERFORM public.notify_members(
      NEW.organization_id, NEW.mentions, 'mention',
      COALESCE(who, 'A colleague') || ' mentioned you in ' || label,
      left(NEW.body, 140), 'channel', chan.id, '/dashboard?module=communication'
    );
  END IF;

  RETURN NEW;
EXCEPTION WHEN others THEN
  -- A failed notification must never lose the message that caused it.
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_notify_message ON messages;
CREATE TRIGGER trg_notify_message
  AFTER INSERT ON messages
  FOR EACH ROW EXECUTE FUNCTION public.notify_message();


