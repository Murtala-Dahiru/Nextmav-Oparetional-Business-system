ALTER TABLE channels
  /**
   * The human name, separate from `name`.
   *
   * `name` is slugged on write so "#General" and "#general" cannot become two
   * channels — right for a channel, wrong for a group called "Q3 Launch Team",
   * which came back as "q3-launch-team" and was title-cased on the way out.
   */
  ADD COLUMN IF NOT EXISTS display_name text,
  ADD COLUMN IF NOT EXISTS topic text NOT NULL DEFAULT '',
  /** Who may post. An announcement channel is one where this is 'admins'. */
  ADD COLUMN IF NOT EXISTS post_policy text NOT NULL DEFAULT 'everyone',
  /** Whether an employee may add themselves, or must be added. */
  ADD COLUMN IF NOT EXISTS join_policy text NOT NULL DEFAULT 'open';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'channels_post_policy_valid') THEN
    ALTER TABLE channels ADD CONSTRAINT channels_post_policy_valid
      CHECK (post_policy IN ('everyone', 'members', 'admins'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'channels_join_policy_valid') THEN
    ALTER TABLE channels ADD CONSTRAINT channels_join_policy_valid
      CHECK (join_policy IN ('open', 'invite'));
  END IF;
END $$;

-- Existing announcement channels described their posting rule through their
-- type and had no column to say so.
UPDATE channels SET post_policy = 'admins'
 WHERE type = 'announcement' AND post_policy = 'everyone';

UPDATE channels SET join_policy = 'invite'
 WHERE type IN ('private', 'direct') AND join_policy = 'open';

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'channel_members_role_valid') THEN
    ALTER TABLE channel_members ADD CONSTRAINT channel_members_role_valid
      CHECK (role IN ('owner', 'admin', 'member'));
  END IF;
END $$;

/** Is the caller a member of this channel? */
CREATE OR REPLACE FUNCTION public.is_channel_member(chan uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM channel_members cm
    JOIN channels c ON c.id = cm.channel_id
    WHERE cm.channel_id = chan
      AND cm.member_id = public.auth_member_id(c.organization_id)
  );
$$;

/** Does the caller administer this channel — its owner, a channel admin, or an org admin? */
CREATE OR REPLACE FUNCTION public.is_channel_admin(chan uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM channels c
    WHERE c.id = chan
      AND (
        public.is_org_admin(c.organization_id)
        OR c.created_by = public.auth_member_id(c.organization_id)
        OR EXISTS (
          SELECT 1 FROM channel_members cm
          WHERE cm.channel_id = c.id
            AND cm.member_id = public.auth_member_id(c.organization_id)
            AND cm.role IN ('owner', 'admin')
        )
      )
  );
$$;

/** May the caller post here? Reads `post_policy`, which the admin screen sets. */
CREATE OR REPLACE FUNCTION public.can_post_to_channel(chan uuid)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
  SELECT EXISTS (
    SELECT 1 FROM channels c
    WHERE c.id = chan
      AND c.is_archived = false
      AND public.can_access_module(c.organization_id, 'communication')
      AND CASE c.post_policy
            WHEN 'everyone' THEN
              c.type IN ('public') OR public.is_channel_member(c.id)
            WHEN 'members'  THEN public.is_channel_member(c.id)
            ELSE                 public.is_channel_admin(c.id)
          END
  );
$$;

GRANT EXECUTE ON FUNCTION public.is_channel_member(uuid)    TO authenticated;
GRANT EXECUTE ON FUNCTION public.is_channel_admin(uuid)     TO authenticated;
GRANT EXECUTE ON FUNCTION public.can_post_to_channel(uuid)  TO authenticated;

/**
 * A private channel's existence is private too.
 *
 * The generated policy in 0005 exposed every channel row to every employee.
 * Messages were protected, so nothing leaked from inside a conversation — but
 * a direct message between two people appeared in everyone's sidebar with
 * both participants' names in the slug, and a private HR channel announced
 * itself by title. This is the narrowing that fixes it.
 */
DROP POLICY IF EXISTS channels_select ON channels;
CREATE POLICY channels_select ON channels FOR SELECT TO authenticated
  USING (
    organization_id = ANY (public.auth_org_ids())
    AND public.can_access_module(organization_id, 'communication')
    AND (
      type IN ('public', 'announcement')
      OR public.is_channel_member(id)
      OR public.is_org_admin(organization_id)
    )
  );

DROP POLICY IF EXISTS channels_update ON channels;
CREATE POLICY channels_update ON channels FOR UPDATE TO authenticated
  USING (organization_id = ANY (public.auth_org_ids())
         AND public.is_channel_admin(id))
  WITH CHECK (organization_id = ANY (public.auth_org_ids()));

DROP POLICY IF EXISTS channels_delete ON channels;
CREATE POLICY channels_delete ON channels FOR DELETE TO authenticated
  USING (organization_id = ANY (public.auth_org_ids())
         AND public.is_channel_admin(id));

/**
 * Membership, split by verb.
 *
 * 0005 had a single FOR ALL policy whose only condition was "the channel is in
 * an organisation you belong to" — so any employee could add themselves to the
 * leadership channel, or remove anybody from anything. Splitting it lets each
 * verb carry its own rule:
 *
 *   insert — channel admins add anyone; an employee may add only themselves,
 *            and only to an open channel
 *   update — you maintain your own read marker and mute flag; admins may
 *            change roles
 *   delete — you may always leave; admins may remove others
 */
DROP POLICY IF EXISTS channel_members_write ON channel_members;

DROP POLICY IF EXISTS channel_members_insert ON channel_members;
CREATE POLICY channel_members_insert ON channel_members FOR INSERT TO authenticated
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM channels c
      WHERE c.id = channel_id
        AND c.organization_id = ANY (public.auth_org_ids())
        AND public.can_access_module(c.organization_id, 'communication')
        AND (
          public.is_channel_admin(c.id)
          OR (member_id = public.auth_member_id(c.organization_id)
              AND c.join_policy = 'open'
              AND c.type IN ('public', 'announcement'))
        )
    )
  );

DROP POLICY IF EXISTS channel_members_update ON channel_members;
CREATE POLICY channel_members_update ON channel_members FOR UPDATE TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM channels c
      WHERE c.id = channel_id
        AND c.organization_id = ANY (public.auth_org_ids())
        AND (member_id = public.auth_member_id(c.organization_id)
             OR public.is_channel_admin(c.id))
    )
  )
  WITH CHECK (
    EXISTS (SELECT 1 FROM channels c
            WHERE c.id = channel_id AND c.organization_id = ANY (public.auth_org_ids()))
  );

DROP POLICY IF EXISTS channel_members_delete ON channel_members;
CREATE POLICY channel_members_delete ON channel_members FOR DELETE TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM channels c
      WHERE c.id = channel_id
        AND c.organization_id = ANY (public.auth_org_ids())
        AND (member_id = public.auth_member_id(c.organization_id)
             OR public.is_channel_admin(c.id))
    )
  );

/**
 * Posting now respects the channel's rule.
 *
 * Previously any member of the organisation could insert a message into any
 * channel id they could guess, including a private one they were not in —
 * `messages_insert` checked only the tenant and the sender. Reading it back
