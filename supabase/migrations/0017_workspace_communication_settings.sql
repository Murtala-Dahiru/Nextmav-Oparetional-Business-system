/**
 * The workspace tree, with the caller's permission resolved per row.
 *
 * The client needs to know whether to show a rename control before the user
 * clicks it; computing that in the browser would mean shipping the sharing
 * rules to it, which is both duplication and a disclosure.
 */
CREATE OR REPLACE VIEW public.v_workspace_tree
WITH (security_invoker = true) AS
SELECT
  p.id,
  p.organization_id,
  p.space_id,
  p.parent_id,
  p.title,
  p.icon,
  p.colour,
  p.kind,
  p.is_folder,
  p.is_template,
  p.is_starred,
  p.visibility,
  p.department_id,
  p.sort_order,
  p.version,
  p.created_by,
  p.last_edited_by,
  p.created_at,
  p.updated_at,
  d.name                        AS department_name,
  editor.full_name              AS last_edited_by_name,
  creator.full_name             AS created_by_name,
  public.page_permission(p.id)  AS permission,
  (SELECT COUNT(*)::int FROM workspace_pages c
    WHERE c.parent_id = p.id AND c.deleted_at IS NULL) AS child_count,
  (SELECT COUNT(*)::int FROM files f
    WHERE f.page_id = p.id AND f.deleted_at IS NULL)   AS file_count,
  (SELECT COUNT(*)::int FROM workspace_page_shares s
    WHERE s.page_id = p.id)                            AS share_count
FROM workspace_pages p
LEFT JOIN departments d           ON d.id = p.department_id
LEFT JOIN organization_members em ON em.id = p.last_edited_by
LEFT JOIN profiles editor         ON editor.id = em.user_id
LEFT JOIN organization_members cm ON cm.id = p.created_by
LEFT JOIN profiles creator        ON creator.id = cm.user_id
WHERE p.deleted_at IS NULL;

GRANT SELECT ON public.v_workspace_tree TO authenticated;

COMMENT ON VIEW public.v_workspace_tree IS
  'Workspace pages and folders with the caller''s effective permission '
  'resolved per row. security_invoker keeps RLS on workspace_pages in force, '
  'so this view can only ever show rows the caller could already read.';

/**
 * Files with their uploader and their place in the workspace.
 *
 * A separate view rather than an embed on the files endpoint, because the same
 * shape is wanted by the project deliverables tab and the HR documents tab,
 * and three PostgREST select strings for one join is how they drift.
 */
CREATE OR REPLACE VIEW public.v_files
WITH (security_invoker = true) AS
SELECT
  f.id,
  f.organization_id,
  f.bucket,
  f.path,
  f.filename,
  f.mime_type,
  f.size_bytes,
  f.description,
  f.version,
  f.page_id,
  f.project_id,
  f.task_id,
  f.ticket_id,
  f.member_id,
  f.is_confidential,
  f.uploaded_by,
  f.created_at,
  f.updated_at,
  p.title       AS folder_title,
  up.full_name  AS uploaded_by_name,
  up.avatar_url AS uploaded_by_avatar,
  proj.name     AS project_name,
  -- Appended rather than inserted: Postgres permits adding columns to the end
  -- of a view definition but not reordering them, and CREATE OR REPLACE on a
  -- view that already exists fails with "cannot change name of view column".
  f.folder,
  f.is_client_visible
FROM files f
LEFT JOIN workspace_pages p        ON p.id = f.page_id
LEFT JOIN projects proj            ON proj.id = f.project_id
LEFT JOIN organization_members om  ON om.id = f.uploaded_by
LEFT JOIN profiles up              ON up.id = om.user_id
WHERE f.deleted_at IS NULL;

GRANT SELECT ON public.v_files TO authenticated;

/**
 * Channel participants, with names, for the members panel.
 *
 * Reading `channel_members` alone gives membership ids; every screen that
 * shows a participant list then has to join to profiles itself, and the two
 * places that already did it spelled the relation differently.
 */
-- Dropped first rather than replaced. `db:apply` re-runs every migration, and
-- 0019 extends this view with further columns — so on the second run this
-- statement would be replacing the wider view with the narrower one, which
-- Postgres refuses with "cannot drop columns from view". Recreating from
-- scratch keeps the chain re-runnable; 0019 then re-adds its columns as it
-- did the first time. Same fix as 0007 needed after 0012 extended
-- v_org_directory.
DROP VIEW IF EXISTS public.v_channel_members CASCADE;

CREATE VIEW public.v_channel_members
WITH (security_invoker = true) AS
SELECT
  cm.id,
  cm.channel_id,
  cm.member_id,
  cm.role,
  cm.is_muted,
  cm.last_read_at,
  cm.joined_at,
  c.organization_id,
  p.full_name,
  p.avatar_url,
  p.email,
  p.job_title,
  p.last_seen_at,
  om.role       AS org_role,
  d.name        AS department_name
FROM channel_members cm
JOIN channels c                   ON c.id = cm.channel_id
JOIN organization_members om      ON om.id = cm.member_id
JOIN profiles p                   ON p.id = om.user_id
LEFT JOIN departments d           ON d.id = om.department_id;

GRANT SELECT ON public.v_channel_members TO authenticated;


