/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  The notification toggles, enforced at the table.
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  ── Why a trigger and not a check in `notify_members()` ──────────────────
 *
 *  `notify_members()` is the *main* way notifications are written, and it is
 *  not the only one: `notify_task_assignment()` and the leave-decision trigger
 *  in 0004 both INSERT into `notifications` directly, and predate it. Putting
 *  the gate in `notify_members()` would have left task assignment — the single
 *  most frequent notification in the product — unaffected by its own switch,
 *  which is exactly the class of "setting that does nothing" this work exists
 *  to remove.
 *
 *  A BEFORE INSERT trigger on the table cannot be bypassed by a call site that
 *  has not heard of it, including ones added later. Returning NULL drops the
 *  row silently, which is what "off" means: filtering on the way *out* would
 *  still cost a row and an index entry per suppressed event, on every task
 *  update in the organisation, forever.
 *
 *  ── The vocabulary ───────────────────────────────────────────────────────
 *
 *  Types are granular and already established — `task_assigned`,
 *  `invoice_overdue`, `leave_requested`. Rather than make the settings screen
 *  invent a coarser vocabulary that would then have to be mapped (and would
 *  drift), a toggle may be keyed either by the exact type or by its family:
 *  `task_assigned` is matched by a key of `task_assigned` first, then `task`.
 *  So one switch labelled "Task activity" governs assignment, completion and
 *  blocking, and a future deployment can still disable one of them precisely.
 *
 *  Absent or malformed settings mean deliver. An organisation that has never
 *  opened the screen, or a type nothing has a toggle for yet, must not go
 *  silent.
 */
CREATE OR REPLACE FUNCTION public.notification_enabled(org uuid, ntype text)
RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  enabled jsonb;
  family  text;
BEGIN
  IF org IS NULL OR ntype IS NULL THEN RETURN true; END IF;

  SELECT value INTO enabled
  FROM org_settings
  WHERE organization_id = org AND key = 'notification_events';

  IF enabled IS NULL THEN RETURN true; END IF;

  -- The exact type wins when it is configured.
  IF enabled ? ntype THEN
    RETURN COALESCE((enabled ->> ntype) <> 'false', true);
  END IF;

  -- Otherwise the family: everything before the first underscore.
  family := split_part(ntype, '_', 1);
  IF enabled ? family THEN
    RETURN COALESCE((enabled ->> family) <> 'false', true);
  END IF;

  RETURN true;
END;
$$;

GRANT EXECUTE ON FUNCTION public.notification_enabled(uuid, text) TO authenticated;

CREATE OR REPLACE FUNCTION public.drop_disabled_notification()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  IF public.notification_enabled(NEW.organization_id, NEW.type) THEN
    RETURN NEW;
  END IF;
  -- Dropped, not raised: a suppressed notification is a configuration choice,
  -- not an error, and must never fail the business write that triggered it.
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_drop_disabled_notification ON notifications;
CREATE TRIGGER trg_drop_disabled_notification
