-- ═══════════════════════════════════════════════════════════════════════════
--  0017 — Finishing the workspace, the communication module, and the settings
--         that were stored but never read
-- ═══════════════════════════════════════════════════════════════════════════
--
--  Three modules were structurally incomplete rather than merely unpolished.
--  Each one had a screen, and behind the screen either nothing to write to or
--  a rule that could not be expressed.
--
--  1. WORKSPACE. `workspace_pages` is a tree of markdown documents and that is
--     all it can hold. The module's own header offers "Document / Spreadsheet
--     / File Vault", but there is no table for a spreadsheet and no table row
--     for an uploaded file, so two of the three tabs rendered fixed sample
--     data and lost everything on reload. Sharing was a button that raised a
--     toast: every page in the organisation was readable by every employee,
--     with no way to say otherwise, which is not a workspace anyone can put
--     an HR folder in.
--
--  2. COMMUNICATION. Channels could be listed and posted to, and nothing else.
--     There was no way to create one, no way to add or remove anybody, and —
--     worse — `channels_select` was generated by the same loop as `companies`
--     and `products`, so it granted SELECT on every row in the organisation.
--     A private channel's messages were protected; its name, topic and
--     existence were not, and a direct message between two colleagues was
--     listed in everybody's sidebar. Sections 4 and 5 below make the channel
--     row as private as its contents, and give a channel an owner, a joining
--     rule and a posting rule.
--
--  3. SETTINGS. `organizations.work_days` is read by the leave logic but not
--     by the register's expected-days figure; `org_settings` holds three keys
--     seeded in 0008 and nothing reads two of them. Section 6 adds the
--     remaining policy keys and backfills them, so the administration screen
--     has a real store behind every control it offers.
--
--  Everything here is additive: no column is dropped, no default changes, and
--  each new table is empty until something writes to it. The two policies that
--  are replaced (`channels_select`, `channel_members_write`) are replaced with
--  strictly narrower ones — nobody loses access to a channel they are in.
-- ═══════════════════════════════════════════════════════════════════════════


-- ───────────────────────────────────────────────────────────────────────────
--  1. Workspace pages: what kind of page, and who may see it
-- ───────────────────────────────────────────────────────────────────────────
--
--  `kind` distinguishes a document from a spreadsheet. Both are pages — they
--  share a title, an icon, a place in the tree, a version history and a
--  sharing rule — so giving spreadsheets their own top-level table would mean
--  duplicating all of that and then keeping the two copies in step. What
--  differs is only where the body lives: a document's is `content`, a
--  spreadsheet's is the column and row tables in section 2.
--
--  `visibility` defaults to 'organization', which is exactly the behaviour
--  every existing page already has. Nothing changes for anything already
--  stored; the other values are opt-in.

ALTER TABLE workspace_pages
  ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'document',
  ADD COLUMN IF NOT EXISTS visibility text NOT NULL DEFAULT 'organization',
  ADD COLUMN IF NOT EXISTS department_id uuid REFERENCES departments(id) ON DELETE SET NULL,
  /**
   * Version counter, maintained by the snapshot trigger in section 3.
   *
   * Held on the page rather than derived with max(version) so concurrent
   * edits cannot both compute the same next number and collide on the
   * unique key.
   */
  ADD COLUMN IF NOT EXISTS version int NOT NULL DEFAULT 1;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pages_kind_valid') THEN
    ALTER TABLE workspace_pages ADD CONSTRAINT pages_kind_valid
      CHECK (kind IN ('document', 'sheet'));
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'pages_visibility_valid') THEN
    ALTER TABLE workspace_pages ADD CONSTRAINT pages_visibility_valid
      CHECK (visibility IN ('inherit', 'organization', 'department', 'private'));
  END IF;
END $$;

COMMENT ON COLUMN workspace_pages.visibility IS
  'inherit = take the parent folder''s rule (the default for anything created '
  'inside a restricted folder); organization = every employee; department = '
  'the named department; private = the owner plus explicit shares.';

/**
 * A folder cannot contain itself.
 *
 * Moving a folder into its own descendant is the one destructive mistake the
 * tree UI makes easy — drag "Marketing" into "Marketing / Campaigns" and the
 * whole subtree detaches from the root and becomes unreachable, while every
 * recursive read spins. Rejected at the database because the move endpoint is
 * not the only thing that can write `parent_id`.
 */
CREATE OR REPLACE FUNCTION public.prevent_page_cycle()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public, pg_temp
AS $$
DECLARE
  ancestor uuid := NEW.parent_id;
  hops     int  := 0;
BEGIN
  IF NEW.parent_id IS NULL THEN
    RETURN NEW;
  END IF;

  IF NEW.parent_id = NEW.id THEN
    RAISE EXCEPTION 'A folder cannot be placed inside itself.'
      USING ERRCODE = 'check_violation';
  END IF;

  WHILE ancestor IS NOT NULL AND hops < 100 LOOP
    IF ancestor = NEW.id THEN
      RAISE EXCEPTION 'A folder cannot be moved inside one of its own subfolders.'
        USING ERRCODE = 'check_violation';
    END IF;
    SELECT parent_id INTO ancestor FROM workspace_pages WHERE id = ancestor;
    hops := hops + 1;
  END LOOP;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prevent_page_cycle ON workspace_pages;
CREATE TRIGGER trg_prevent_page_cycle
  BEFORE INSERT OR UPDATE OF parent_id ON workspace_pages
  FOR EACH ROW EXECUTE FUNCTION public.prevent_page_cycle();

-- ── Explicit shares ────────────────────────────────────────────────────────
--
--  A share names either a person or a department, never both. Two nullable
--  columns with a CHECK rather than two tables, because every read wants them
--  together — "may this person open this folder" is one question.

CREATE TABLE IF NOT EXISTS workspace_page_shares (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  page_id         uuid NOT NULL REFERENCES workspace_pages(id) ON DELETE CASCADE,
  member_id       uuid REFERENCES organization_members(id) ON DELETE CASCADE,
  department_id   uuid REFERENCES departments(id) ON DELETE CASCADE,
  /**
   * view   — open and read, including everything inside a shared folder
   * edit   — change the body, add pages inside a shared folder
   * manage — the above plus re-sharing and deleting
   */
  permission      text NOT NULL DEFAULT 'view'
                  CHECK (permission IN ('view', 'edit', 'manage')),
  granted_by      uuid REFERENCES organization_members(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT share_has_exactly_one_subject
    CHECK ((member_id IS NULL) <> (department_id IS NULL))
);

-- Two shares of the same page to the same subject would make "what may they
-- do" ambiguous. Partial uniques because NULL is not equal to NULL.
CREATE UNIQUE INDEX IF NOT EXISTS uq_page_share_member
  ON workspace_page_shares (page_id, member_id) WHERE member_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_page_share_department
  ON workspace_page_shares (page_id, department_id) WHERE department_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_page_shares_page ON workspace_page_shares (page_id);

/**
 * ═══════════════════════════════════════════════════════════════════════════
 *  The effective permission a caller holds on a page.
 * ═══════════════════════════════════════════════════════════════════════════
 *
 *  ── Why this takes the row's columns rather than just its id ─────────────
 *
 *  The obvious signature is `page_permission(page uuid)`, looking the row up
 *  itself. That version cannot be used in the row-level policies, and the
 *  reason is worth writing down because the failure is silent and confusing.
 *
 *  A `STABLE` function sees the snapshot taken at the start of the statement.
 *  During `INSERT ... RETURNING`, Postgres applies the SELECT policy to the
 *  new row — but a STABLE function called from that policy cannot see the row
 *  the statement is in the middle of inserting. It looks it up, finds nothing,
 *  and returns NULL. The policy then reads that as "no access" and the insert
 *  fails with 42501, *new row violates row-level security policy* — for a row
 *  the caller had every right to create. Every workspace create returned 403.
 *
 *  Marking it VOLATILE would fix the visibility and cost a fresh snapshot per
 *  row, on a tree query that touches every page in the workspace.
 *
 *  So the policies pass the columns they already have in hand. Only the walk
 *  up the ancestry needs a lookup, and an ancestor is always a committed row.
 *
 *  Returns NULL when the caller has no access at all. Administrators and the
 *  page's own creator always resolve 'manage' — an owner locking themselves
 *  out of their own folder is not a security property, it is a support ticket.
 */
CREATE OR REPLACE FUNCTION public.page_grant(
  org     uuid,
  vis     text,
  dept    uuid,
  creator uuid,
  parent  uuid,
  page    uuid
)
RETURNS text
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  me      uuid;
  my_dept uuid;
  granted text;
BEGIN
  IF org IS NULL THEN RETURN NULL; END IF;

  IF NOT public.can_access_module(org, 'workspace') THEN
    RETURN NULL;
  END IF;

  IF public.is_org_admin(org) THEN RETURN 'manage'; END IF;

  me      := public.auth_member_id(org);
  my_dept := public.auth_department_id(org);

  IF creator IS NOT NULL AND creator = me THEN
    RETURN 'manage';
  END IF;

  -- An explicit share on this page. Empty for a row being inserted, which is
  -- correct: nothing can have been shared with anybody yet.
  SELECT s.permission INTO granted
  FROM workspace_page_shares s
  WHERE s.page_id = page
    AND (s.member_id = me OR (s.department_id IS NOT NULL AND s.department_id = my_dept))
  -- The most generous share wins when somebody is named both directly and
  -- through their department.
  ORDER BY CASE s.permission WHEN 'manage' THEN 3 WHEN 'edit' THEN 2 ELSE 1 END DESC
  LIMIT 1;

  IF granted IS NOT NULL THEN RETURN granted; END IF;

  IF vis = 'organization' THEN
    RETURN 'edit';
  ELSIF vis = 'department' THEN
    IF my_dept IS NOT NULL AND dept = my_dept THEN RETURN 'edit'; END IF;
    RETURN NULL;
  ELSIF vis = 'private' THEN
    RETURN NULL;
  END IF;

  -- 'inherit': take the parent folder's answer. A page that inherits all the
  -- way to the root with nothing decided is a normal organisation-visible page.
  IF parent IS NULL THEN RETURN 'edit'; END IF;
  RETURN public.page_permission(parent);
END;
$$;

/**
 * The same question, for a page that is already stored.
 *
 * This is what the view and the endpoints call — they have an id and want the
 * answer. It looks the row up and delegates, so there is exactly one
 * description of the rule.
 */
CREATE OR REPLACE FUNCTION public.page_permission(page uuid)
RETURNS text
LANGUAGE plpgsql STABLE SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  cur workspace_pages;
BEGIN
  SELECT * INTO cur FROM workspace_pages WHERE id = page;
  IF NOT FOUND THEN RETURN NULL; END IF;

  RETURN public.page_grant(
    cur.organization_id, cur.visibility, cur.department_id,
    cur.created_by, cur.parent_id, cur.id
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.page_permission(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.page_grant(uuid, text, uuid, uuid, uuid, uuid) TO authenticated;

ALTER TABLE workspace_page_shares ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_page_shares FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS page_shares_select ON workspace_page_shares;
CREATE POLICY page_shares_select ON workspace_page_shares FOR SELECT TO authenticated
  USING (organization_id = ANY (public.auth_org_ids())
         AND public.page_permission(page_id) IS NOT NULL);

-- Only someone who could re-share may create or revoke a share.
DROP POLICY IF EXISTS page_shares_write ON workspace_page_shares;
CREATE POLICY page_shares_write ON workspace_page_shares FOR ALL TO authenticated
  USING (organization_id = ANY (public.auth_org_ids())
         AND public.page_permission(page_id) = 'manage')
  WITH CHECK (organization_id = ANY (public.auth_org_ids())
              AND public.page_permission(page_id) = 'manage');

-- ── Page policies, replaced to honour visibility ───────────────────────────
--
--  The generated policies in 0005 granted every employee full read and write
--  on every page. These keep that outcome for organisation-visible pages —
--  which is all of them today — and enforce the new rules for the rest.

--
--  Every policy below passes the row's own columns to `page_grant()` rather
--  than asking `page_permission(id)` to look them up. See the comment on
--  `page_grant` — a STABLE lookup cannot see the row an INSERT is in the
--  middle of writing, and `INSERT ... RETURNING` applies the SELECT policy to
--  exactly that row.

DROP POLICY IF EXISTS workspace_pages_select ON workspace_pages;
CREATE POLICY workspace_pages_select ON workspace_pages FOR SELECT TO authenticated
  USING (
    organization_id = ANY (public.auth_org_ids())
    AND public.page_grant(organization_id, visibility, department_id,
                          created_by, parent_id, id) IS NOT NULL
  );

DROP POLICY IF EXISTS workspace_pages_insert ON workspace_pages;
CREATE POLICY workspace_pages_insert ON workspace_pages FOR INSERT TO authenticated
  WITH CHECK (
    organization_id = ANY (public.auth_org_ids())
    AND public.can_access_module(organization_id, 'workspace')
    -- Creating inside a folder requires the right to write in that folder.
    AND (parent_id IS NULL OR public.page_permission(parent_id) IN ('edit', 'manage'))
  );

DROP POLICY IF EXISTS workspace_pages_update ON workspace_pages;
CREATE POLICY workspace_pages_update ON workspace_pages FOR UPDATE TO authenticated
  USING (
    organization_id = ANY (public.auth_org_ids())
    AND public.page_grant(organization_id, visibility, department_id,
                          created_by, parent_id, id) IN ('edit', 'manage')
  )
  WITH CHECK (organization_id = ANY (public.auth_org_ids()));

/**
 * Deletion is narrower than editing.
 *
 * 0005 allowed any manager to delete any page in the organisation. A page you
 * cannot even open should not be one you can destroy, so this asks for
 * 'manage' — which administrators, the creator, and anyone explicitly granted
 * it all hold.
 */
DROP POLICY IF EXISTS workspace_pages_delete ON workspace_pages;
CREATE POLICY workspace_pages_delete ON workspace_pages FOR DELETE TO authenticated
  USING (
    organization_id = ANY (public.auth_org_ids())
    AND public.page_grant(organization_id, visibility, department_id,
                          created_by, parent_id, id) = 'manage'
  );


-- ───────────────────────────────────────────────────────────────────────────
--  2. Spreadsheets
-- ───────────────────────────────────────────────────────────────────────────
--
--  A column table and a row table, with the cells held as jsonb keyed by
--  column id.
--
--  The alternative — a `cells` table with one row per cell — is the textbook
--  answer and the wrong one here: a 40-column, 500-row sheet becomes 20,000
--  rows to read, order and reassemble on every open, and every column rename
--  is a mass update. Keying the jsonb by column id rather than by column name
--  is what makes renaming a column free and makes deleting one leave no
--  dangling references that a reader can see.
--
--  Column definitions stay relational because they are what the UI enumerates,
--  what validation reads, and what has to keep a stable order.

CREATE TABLE IF NOT EXISTS workspace_sheet_columns (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  page_id         uuid NOT NULL REFERENCES workspace_pages(id) ON DELETE CASCADE,
  name            text NOT NULL CHECK (btrim(name) <> ''),
  /**
   * The cell editor to render and how to sort the column.
   *
   * 'select' carries its choices in `options`; 'currency' formats with the
   * organisation's currency, so a finance sheet does not have to repeat the
   * symbol in every cell.
   */
  type            text NOT NULL DEFAULT 'text'
                  CHECK (type IN ('text','number','currency','date','select','checkbox','member','url')),
  options         jsonb NOT NULL DEFAULT '[]'::jsonb,
  width           int NOT NULL DEFAULT 180 CHECK (width BETWEEN 60 AND 900),
  position        int NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sheet_columns_page
  ON workspace_sheet_columns (page_id, position);

CREATE TABLE IF NOT EXISTS workspace_sheet_rows (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  page_id         uuid NOT NULL REFERENCES workspace_pages(id) ON DELETE CASCADE,
  /** { "<column uuid>": <value> } — absent key means an empty cell. */
  cells           jsonb NOT NULL DEFAULT '{}'::jsonb,
  position        int NOT NULL DEFAULT 0,
  created_by      uuid REFERENCES organization_members(id) ON DELETE SET NULL,
  updated_by      uuid REFERENCES organization_members(id) ON DELETE SET NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sheet_rows_page
  ON workspace_sheet_rows (page_id, position);

/**
 * Dropping a column removes its cells.
 *
 * Without this the jsonb keeps the deleted column's values forever: invisible,
 * exported anyway, and reinstated the moment somebody re-adds a column that
 * happens to reuse the id. Cheap because it touches only the sheet concerned.
 */
CREATE OR REPLACE FUNCTION public.prune_sheet_column()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
BEGIN
  UPDATE workspace_sheet_rows
     SET cells = cells - OLD.id::text
   WHERE page_id = OLD.page_id
     AND cells ? OLD.id::text;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_prune_sheet_column ON workspace_sheet_columns;
CREATE TRIGGER trg_prune_sheet_column
  AFTER DELETE ON workspace_sheet_columns
  FOR EACH ROW EXECUTE FUNCTION public.prune_sheet_column();

-- Both tables inherit the page's sharing rule rather than restating it, so a
-- folder shared with HR carries its spreadsheets with it.
ALTER TABLE workspace_sheet_columns ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_sheet_columns FORCE ROW LEVEL SECURITY;
ALTER TABLE workspace_sheet_rows ENABLE ROW LEVEL SECURITY;
ALTER TABLE workspace_sheet_rows FORCE ROW LEVEL SECURITY;

