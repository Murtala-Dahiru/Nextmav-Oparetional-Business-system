  FOR EACH ROW EXECUTE FUNCTION public.drop_disabled_notification();

/**
 * `departments.head_id` gains the foreign key its own comment claims.
 *
 * The column has existed since 0001, described there as "a membership, not a
 * bare user: it must be someone in this org" — and carrying no constraint at
 * all. Nothing could write it until now, so nothing had tested the claim. With
 * the administration screen able to assign a manager, an unconstrained uuid
 * column would accept a membership from another tenant, which is a
 * cross-organisation reference in the middle of the org chart.
 *
 * ON DELETE SET NULL rather than CASCADE: removing a person should leave the
 * department without a manager, not delete the department.
 */
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'departments_head_fk') THEN
    -- Anything already pointing nowhere is cleared first, or the constraint
    -- cannot be added.
    UPDATE departments d SET head_id = NULL
     WHERE head_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM organization_members om WHERE om.id = d.head_id);

    ALTER TABLE departments
      ADD CONSTRAINT departments_head_fk
      FOREIGN KEY (head_id) REFERENCES organization_members(id) ON DELETE SET NULL;
  END IF;
END $$;


